import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const toolsDir = join(root, 'app/tools');
mkdirSync(toolsDir, { recursive: true });

const ids = existsSync(toolsDir)
  ? readdirSync(toolsDir, { withFileTypes: true })
      .filter((e) => e.isDirectory() && existsSync(join(toolsDir, e.name, 'manifest.ts')))
      .map((e) => e.name)
      .sort()
  : [];

const header = '// generated by scripts/gen-registry.mjs — do not edit\n';

const registry =
  header +
  `import type { RegisteredModule } from '@/platform/define';\n` +
  ids
    .map((id, i) => `import m${i} from '@/app/tools/${id}/manifest';\nimport a${i} from '@/app/tools/${id}/access';`)
    .join('\n') +
  (ids.length ? '\n' : '') +
  `export const modules: RegisteredModule[] = [\n` +
  ids.map((_, i) => `  { manifest: m${i}, access: a${i} },`).join('\n') +
  `\n];\n`;
writeFileSync(join(root, 'platform/registry.generated.ts'), registry);

const withActions = ids.filter((id) => existsSync(join(toolsDir, id, 'actions.ts')));
const actions =
  header +
  withActions.map((id, i) => `import * as x${i} from '@/app/tools/${id}/actions';`).join('\n') +
  (withActions.length ? '\n' : '') +
  `export const moduleActions: { module: string; actions: Record<string, unknown> }[] = [\n` +
  withActions.map((id, i) => `  { module: '${id}', actions: x${i} },`).join('\n') +
  `\n];\n`;
writeFileSync(join(root, 'platform/actions.generated.ts'), actions);

console.log(`registry: ${ids.length} module(s)`);
